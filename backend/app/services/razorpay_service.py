class RazorpayService:
    """Production-grade Razorpay payment gateway, orders, signature verification, and webhook engine."""

    @staticmethod
    def is_configured() -> bool:
        """Returns True if real Razorpay API keys are configured in environment."""
        return bool(
            settings.RAZORPAY_KEY_ID
            and settings.RAZORPAY_KEY_SECRET
            and settings.RAZORPAY_KEY_ID.startswith("rzp_")
        )

    @staticmethod
    def get_public_key() -> str:
        """Returns public Key ID to pass to frontend Razorpay checkout modal."""
        return settings.RAZORPAY_KEY_ID or "rzp_test_placeholder"

    @staticmethod
    def get_currency() -> str:
        """Returns active billing currency."""
        return (settings.RAZORPAY_CURRENCY or "USD").upper()

    @staticmethod
    def verify_signature(order_id: str, payment_id: str, signature: str) -> bool:
        """Verifies HMAC-SHA256 signature generated by Razorpay Checkout."""
        if not settings.RAZORPAY_KEY_SECRET:
            # In local sandbox/test mode without keys, allow test signatures
            if signature.startswith("test_sig_") or order_id.startswith("order_test_"):
                return True
            return False

        generated_signature = hmac.new(
            settings.RAZORPAY_KEY_SECRET.encode("utf-8"),
            f"{order_id}|{payment_id}".encode("utf-8"),
            hashlib.sha256,
        ).hexdigest()

        return hmac.compare_digest(generated_signature, signature)

    @staticmethod
    def verify_webhook_signature(raw_body: bytes, signature: str) -> bool:
        """Verifies Razorpay webhook signature header against body."""
        secret = settings.RAZORPAY_WEBHOOK_SECRET or settings.RAZORPAY_KEY_SECRET
        if not secret:
            return False

        expected_signature = hmac.new(
            secret.encode("utf-8"),
            raw_body,
            hashlib.sha256,
        ).hexdigest()

        return hmac.compare_digest(expected_signature, signature)

    @staticmethod
    async def create_plan_order(
        db: AsyncSession,
        workspace_id: str,
        plan_code: str,
        user_email: str,
        billing_cycle: str = "monthly",
        user_id: Optional[str] = None,
    ) -> Dict[str, Any]:
        """Creates a Razorpay Order for a recurring plan upgrade."""
        plan = await PlanService.get_plan_by_code(db, plan_code)
        if not plan:
            raise ValueError(f"Invalid plan code: {plan_code}")

        if plan.code == PlanCode.FREE.value:
            # Free plan activates immediately
            await RazorpayService.activate_free_plan(db, workspace_id, user_id)
            return {
                "order_id": f"order_free_{uuid.uuid4().hex[:10]}",
                "amount": 0,
                "currency": RazorpayService.get_currency(),
                "key_id": RazorpayService.get_public_key(),
                "plan_code": PlanCode.FREE.value,
                "is_free": True,
                "message": "Free plan activated successfully.",
            }

        # Calculate price based on billing cycle (20% discount on annual)
        price = plan.price_monthly
        if billing_cycle == "annual":
            price = round(plan.price_monthly * 0.8 * 12, 2)

        # Amount in smallest currency unit (e.g. cents for USD, paise for INR)
        amount_in_subunits = int(round(price * 100))
        currency = RazorpayService.get_currency()
        receipt_id = f"rcpt_plan_{uuid.uuid4().hex[:10]}"

        order_id = f"order_test_{uuid.uuid4().hex[:12]}"

        # Call live Razorpay API if configured
        if RazorpayService.is_configured():
            try:
                auth = (settings.RAZORPAY_KEY_ID, settings.RAZORPAY_KEY_SECRET)
                payload = {
                    "amount": amount_in_subunits,
                    "currency": currency,
                    "receipt": receipt_id,
                    "notes": {
                        "workspace_id": workspace_id,
                        "user_id": user_id or "",
                        "plan_code": plan.code,
                        "billing_cycle": billing_cycle,
                        "user_email": user_email,
                        "type": "subscription_upgrade",
                    },
                }
                async with httpx.AsyncClient(timeout=20.0) as client:
                    resp = await client.post(
                        "https://api.razorpay.com/v1/orders",
                        json=payload,
                        auth=auth,
                    )
                    if resp.status_code in (200, 201):
                        order_data = resp.json()
                        order_id = order_data.get("id", order_id)
                    else:
                        logger.error("Razorpay order creation failed: %s %s", resp.status_code, resp.text)
                        raise ValueError(f"Razorpay error: {resp.text}")
            except Exception as e:
                logger.error("Error connecting to Razorpay API: %s", e)
                if not order_id.startswith("order_test_"):
                    raise

        # Record pending payment in database
        payment = Payment(
            id=str(uuid.uuid4()),
            workspace_id=workspace_id,
            user_id=user_id,
            provider="razorpay",
            provider_payment_id=order_id,
            amount=price,
            currency=currency,
            status=PaymentStatus.PENDING.value,
            payment_type="subscription",
            payment_metadata={
                "order_id": order_id,
                "plan_code": plan.code,
                "billing_cycle": billing_cycle,
                "user_email": user_email,
            },
        )
        db.add(payment)
        await db.commit()

        return {
            "order_id": order_id,
            "amount": amount_in_subunits,
            "amount_display": price,
            "currency": currency,
            "key_id": RazorpayService.get_public_key(),
            "plan_code": plan.code,
            "plan_name": plan.name,
            "billing_cycle": billing_cycle,
            "user_email": user_email,
            "is_free": False,
            "name": "SEOSensing",
            "description": f"{plan.name} Plan ({billing_cycle.capitalize()}) - {plan.monthly_credits:,} credits/mo",
        }

