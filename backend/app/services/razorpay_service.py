    @staticmethod
    async def verify_and_fulfill_payment(
        db: AsyncSession,
        workspace_id: str,
        razorpay_order_id: str,
        razorpay_payment_id: str,
        razorpay_signature: str,
        user_id: Optional[str] = None,
        plan_code: Optional[str] = None,
        pack_credits: Optional[int] = None,
        billing_cycle: str = "monthly",
    ) -> Dict[str, Any]:
        """Verifies signature and immediately activates subscription or credits wallet."""
        is_valid = RazorpayService.verify_signature(
            order_id=razorpay_order_id,
            payment_id=razorpay_payment_id,
            signature=razorpay_signature,
        )

        if not is_valid:
            logger.warning("Invalid Razorpay payment signature for order %s", razorpay_order_id)
            raise ValueError("Invalid payment signature. Payment verification failed.")

        # Check for existing payment record or create
        stmt = select(Payment).where(Payment.provider_payment_id == razorpay_order_id)
        res = await db.execute(stmt)
        payment = res.scalar_one_or_none()

        now = utc_now()

        if payment:
            payment.status = PaymentStatus.SUCCEEDED.value
            payment.payment_metadata = {
                **(payment.payment_metadata or {}),
                "razorpay_payment_id": razorpay_payment_id,
                "razorpay_signature": razorpay_signature,
                "verified_at": now.isoformat(),
            }
        else:
            payment = Payment(
                id=str(uuid.uuid4()),
                workspace_id=workspace_id,
                user_id=user_id,
                provider="razorpay",
                provider_payment_id=razorpay_payment_id,
                amount=0.0,
                currency=RazorpayService.get_currency(),
                status=PaymentStatus.SUCCEEDED.value,
                payment_type="subscription" if plan_code else "credit_topup",
                payment_metadata={
                    "razorpay_order_id": razorpay_order_id,
                    "razorpay_payment_id": razorpay_payment_id,
                    "razorpay_signature": razorpay_signature,
                },
            )
            db.add(payment)

        # Fulfill Subscription Upgrade
        if plan_code and plan_code != PlanCode.FREE.value:
            plan = await PlanService.get_plan_by_code(db, plan_code)
            if not plan:
                raise ValueError(f"Plan not found: {plan_code}")

            period_start = now
            period_end = now + timedelta(days=365 if billing_cycle == "annual" else 30)

            # Update or create active Subscription
            sub_stmt = select(Subscription).where(Subscription.workspace_id == workspace_id)
            sub_res = await db.execute(sub_stmt)
            sub = sub_res.scalar_one_or_none()

            if sub:
                sub.plan_id = plan.id
                sub.provider = "razorpay"
                sub.provider_subscription_id = razorpay_order_id
                sub.status = SubscriptionStatus.ACTIVE.value
                sub.billing_interval = billing_cycle
                sub.current_period_start = period_start
                sub.current_period_end = period_end
                sub.cancel_at_period_end = False
            else:
                sub = Subscription(
                    id=str(uuid.uuid4()),
                    workspace_id=workspace_id,
                    plan_id=plan.id,
                    provider="razorpay",
                    provider_subscription_id=razorpay_order_id,
                    status=SubscriptionStatus.ACTIVE.value,
                    billing_interval=billing_cycle,
                    current_period_start=period_start,
                    current_period_end=period_end,
                    cancel_at_period_end=False,
                )
                db.add(sub)

            # Allocate monthly credits + apply rollover
            await CreditAllocationService.allocate_subscription_period(
                db=db,
                workspace_id=workspace_id,
                plan=plan,
                period_start=period_start,
                period_end=period_end,
                user_id=user_id,
            )

            # Create Invoice record
            invoice_num = f"INV-RZP-{razorpay_payment_id[-8:].upper()}"
            invoice = Invoice(
                id=str(uuid.uuid4()),
                workspace_id=workspace_id,
                user_id=user_id,
                provider_invoice_id=razorpay_payment_id,
                invoice_number=invoice_num,
                amount=payment.amount if payment.amount > 0 else plan.price_monthly,
                currency=RazorpayService.get_currency(),
                status="paid",
                period_start=period_start,
                period_end=period_end,
            )
            db.add(invoice)

            await db.commit()
            wallet = await CreditWalletService.get_or_create_wallet(db, workspace_id, user_id)

            return {
                "success": True,
                "verified": True,
                "type": "subscription",
                "plan_code": plan.code,
                "plan_name": plan.name,
                "message": f"Successfully upgraded to {plan.name} Plan! Your wallet has been credited.",
                "available_credits": wallet.available_credits,
                "invoice_number": invoice_num,
            }

        # Fulfill One-Time Credit Pack Purchase
        elif pack_credits:
            pack = ONE_TIME_CREDIT_PACKS.get(pack_credits)
            if not pack:
                raise ValueError(f"Invalid credit pack size: {pack_credits}")

            tx = await CreditWalletService.add_credits_atomic(
                db=db,
                workspace_id=workspace_id,
                amount=pack_credits,
                type=CreditTransactionType.PURCHASE.value,
                operation="razorpay_credit_purchase",
                description=f"Razorpay Purchase: {pack['name']} (+{pack_credits:,} credits)",
                user_id=user_id,
                metadata={
                    "razorpay_order_id": razorpay_order_id,
                    "razorpay_payment_id": razorpay_payment_id,
                    "price_paid": pack["price"],
                },
                idempotency_key=f"rzp_tx_{razorpay_payment_id}",
            )

            # Record purchase
            purchase = CreditPurchase(
                id=str(uuid.uuid4()),
                workspace_id=workspace_id,
                user_id=user_id,
                credits_amount=pack_credits,
                price_paid=pack["price"],
                currency=RazorpayService.get_currency(),
                provider_payment_id=razorpay_payment_id,
                status=PaymentStatus.SUCCEEDED.value,
            )
            db.add(purchase)

            # Create Invoice
            invoice_num = f"INV-RZP-{razorpay_payment_id[-8:].upper()}"
            invoice = Invoice(
                id=str(uuid.uuid4()),
                workspace_id=workspace_id,
                user_id=user_id,
                provider_invoice_id=razorpay_payment_id,
                invoice_number=invoice_num,
                amount=pack["price"],
                currency=RazorpayService.get_currency(),
                status="paid",
            )
            db.add(invoice)

            await db.commit()
            wallet = await CreditWalletService.get_or_create_wallet(db, workspace_id, user_id)

            return {
                "success": True,
                "verified": True,
                "type": "credit_topup",
                "pack_credits": pack_credits,
                "message": f"Successfully purchased {pack_credits:,} credits! Credits are now available in your wallet.",
                "available_credits": wallet.available_credits,
                "invoice_number": invoice_num,
            }

        await db.commit()
        wallet = await CreditWalletService.get_or_create_wallet(db, workspace_id, user_id)

        return {
            "success": True,
            "message": "Payment verified successfully.",
            "available_credits": wallet.available_credits,
        }

    @staticmethod
    async def activate_free_plan(
        db: AsyncSession, workspace_id: str, user_id: Optional[str] = None
    ) -> bool:
        """Activates default Free plan (50 credits/mo)."""
        free_plan = await PlanService.get_plan_by_code(db, PlanCode.FREE.value)
        if not free_plan:
            plans = await PlanService.ensure_seed_plans(db)
            free_plan = next(p for p in plans if p.code == PlanCode.FREE.value)

        now = utc_now()
        stmt = select(Subscription).where(Subscription.workspace_id == workspace_id)
        res = await db.execute(stmt)
        sub = res.scalar_one_or_none()

        if sub:
            sub.plan_id = free_plan.id
            sub.provider = "razorpay"
            sub.status = SubscriptionStatus.ACTIVE.value
            sub.current_period_start = now
            sub.current_period_end = now + timedelta(days=30)
        else:
            sub = Subscription(
                id=str(uuid.uuid4()),
                workspace_id=workspace_id,
                plan_id=free_plan.id,
                provider="razorpay",
                status=SubscriptionStatus.ACTIVE.value,
                billing_interval="monthly",
                current_period_start=now,
                current_period_end=now + timedelta(days=30),
            )
            db.add(sub)

        # Initialize or update wallet
        wallet = await CreditWalletService.get_or_create_wallet(db, workspace_id, user_id)
        wallet.monthly_credits = free_plan.monthly_credits
        wallet.available_credits = max(wallet.available_credits, free_plan.monthly_credits)

        await db.commit()
        return True

    @staticmethod
    async def process_webhook_event(
        db: AsyncSession, event_payload: Dict[str, Any], raw_body: bytes, signature: str
    ) -> Dict[str, Any]:
        """Processes server-to-server Razorpay webhooks idempotently."""
        event_id = event_payload.get("event_id") or event_payload.get("id") or str(uuid.uuid4())
        event_type = event_payload.get("event", "unknown")

        # Idempotency check
        stmt = select(BillingWebhookEvent).where(BillingWebhookEvent.event_id == event_id)
        res = await db.execute(stmt)
        if res.scalar_one_or_none():
            return {"status": "already_processed", "event_id": event_id}

        # Verify signature if webhook secret is configured
        if settings.RAZORPAY_WEBHOOK_SECRET:
            if not RazorpayService.verify_webhook_signature(raw_body, signature):
                logger.warning("Invalid Razorpay webhook signature for event %s", event_id)
                raise ValueError("Invalid webhook signature")

        webhook_event = BillingWebhookEvent(
            id=str(uuid.uuid4()),
            event_id=event_id,
            provider="razorpay",
            event_type=event_type,
            raw_payload=event_payload,
            status="processing",
        )
        db.add(webhook_event)
        await db.commit()

        try:
            payload_data = event_payload.get("payload", {})

            # Handle payment.captured / order.paid
            if event_type in ("order.paid", "payment.captured"):
                payment_entity = payload_data.get("payment", {}).get("entity", {})
                notes = payment_entity.get("notes", {})
                workspace_id = notes.get("workspace_id")
                plan_code = notes.get("plan_code")
                pack_credits_str = notes.get("pack_credits")
                order_id = payment_entity.get("order_id", "")
                payment_id = payment_entity.get("id", "")

                if workspace_id:
                    pack_credits = int(pack_credits_str) if pack_credits_str else None
                    await RazorpayService.verify_and_fulfill_payment(
                        db=db,
                        workspace_id=workspace_id,
                        razorpay_order_id=order_id,
                        razorpay_payment_id=payment_id,
                        razorpay_signature="webhook_verified",
                        plan_code=plan_code,
                        pack_credits=pack_credits,
                        billing_cycle=notes.get("billing_cycle", "monthly"),
                    )

            webhook_event.status = "processed"
            webhook_event.processed_at = utc_now()
            await db.commit()
            return {"status": "success", "event_type": event_type}

        except Exception as e:
            logger.error("Error processing Razorpay webhook event %s: %s", event_id, e)
            webhook_event.status = "failed"
            webhook_event.error_message = str(e)
            await db.commit()
            raise
